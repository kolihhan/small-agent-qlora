"""Synthetic end-to-end agent → RecordingModel → trace → SAFE artifact smoke.

No real AppWorld model, accounts, passwords, networking, or evaluator.
The fake password/token deliberately flow through model-visible tool responses,
tool-call arguments, RecordingModel.messages and AgentRuntime.trace; the ONLY
uploaded output is strict numeric/boolean evidence generated by the safe
exporter. Exceptions contain the fake password but are never logged.
"""
from __future__ import annotations

from contextlib import redirect_stdout,redirect_stderr
import io
import json
from pathlib import Path
import tempfile

from gaia_small_agent.agent.loop import AgentRuntime
from gaia_small_agent.agent.types import AssistantTurn, ToolCall, ModelRuntimeError
from gaia_small_agent.tools.appworld_tool import AppWorldDocsTool,AppWorldCallTool
from gaia_small_agent.tools.appworld_parity_safe_export import (
    aggregate_private_run,write_safe_report,safe_exception_category,
)
from scripts.appworld_train_first_feedback_fork import RecordingModel

_SYNTHETIC_PASSWORD="SYNTHETIC-PASSWORD-PRIVATE-SENTINEL-90823"
_SYNTHETIC_TOKEN="SYNTHETIC-TOKEN-PRIVATE-SENTINEL-77718"
_SYNTHETIC_PROFILE="synthetic-private-sentinel@example.invalid"
_SECRET=(_SYNTHETIC_PASSWORD,_SYNTHETIC_TOKEN,_SYNTHETIC_PROFILE)


def _doc(params=()):
    return {"method":"POST","path":"/synthetic", "parameters":list(params),
            "description":"Fake official-looking API, not a real account"}


class _Requester:
    def request(self,**kw):
        name=kw["_api_name"]
        if name=="show_profile":
            return {"email":_SYNTHETIC_PROFILE}
        if name=="show_account_passwords":
            return {"account_passwords":[{"account":"calendar","password":_SYNTHETIC_PASSWORD}]}
        if name=="login":
            assert kw.get("password")==_SYNTHETIC_PASSWORD
            return {"access_token":_SYNTHETIC_TOKEN}
        if name=="read_data":
            assert kw.get("access_token")==_SYNTHETIC_TOKEN
            return {"records":[{"safe_fake_record":True}]}
        raise ValueError("SYNTHETIC-PASSWORD-PRIVATE-SENTINEL-90823 would be unsafe to log")


def _world():
    from types import SimpleNamespace
    return SimpleNamespace(task=SimpleNamespace(
        allowed_apps=["supervisor","calendar"],
        api_docs={
            "supervisor":{
                "show_profile":_doc(),
                "show_account_passwords":_doc(),
                "complete_task":_doc(),
            },
            "calendar":{
                "login":_doc([{"name":"password","required":True,"type":"string"}]),
                "read_data":_doc([{"name":"access_token","required":True,"type":"string"}]),
            },
        }),requester=_Requester())


class _SyntheticAgentModel:
    def __init__(self,fail_after_password:bool=False):
        self.n=0
        self.fail_after_password=fail_after_password

    def complete(self,messages,tools):
        self.n+=1
        if self.n==1:
            return AssistantTurn("",[ToolCall("a","appworld_call",{
                "app":"supervisor","api":"show_profile","arguments":{}})])
        if self.n==2:
            return AssistantTurn("",[ToolCall("b","appworld_call",{
                "app":"supervisor","api":"show_account_passwords","arguments":{}})])
        # This is a deliberately observed secret in a model-facing message.
        # It must not appear in safe summaries or CI artifacts.
        assert any(m.get("role")=="tool" and _SYNTHETIC_PASSWORD in m.get("content","")
                   for m in messages)
        if self.fail_after_password:
            raise ModelRuntimeError("model_error","SYNTHETIC-PASSWORD-PRIVATE-SENTINEL-90823")
        if self.n==3:
            return AssistantTurn("",[ToolCall("c","appworld_call",{
                "app":"calendar","api":"login",
                "arguments":{"password":_SYNTHETIC_PASSWORD}})])
        if self.n==4:
            return AssistantTurn("",[ToolCall("d","appworld_call",{
                "app":"calendar","api":"read_data",
                "arguments":{"access_token":_SYNTHETIC_TOKEN}})])
        # Even a malicious final model answer is excluded from safe artifact.
        return AssistantTurn("Task done. "+_SYNTHETIC_PASSWORD+" "+_SYNTHETIC_TOKEN)

    def complete_final(self,messages,tools):
        return self.complete(messages,tools)


def exercise_synthetic_private_workflow(workspace:Path,*,fail_after_password=False)->dict:
    world=_world()
    api=AppWorldCallTool(world,official_supervisor_parity=True,
                         report_http_failures=True,max_calls=48)
    recorder=RecordingModel(_SyntheticAgentModel(fail_after_password))
    # This inner trace can contain secret-valued tool_result.content and
    # tool_call.arguments. Never use AgentResult.to_dict() for exported data.
    result=AgentRuntime(recorder,[
        AppWorldDocsTool(world,official_supervisor_parity=True),api,
    ],max_steps=20).run(
        "Fake sandbox task. No sensitive data may leave memory.",workspace/"private")
    assert any(_SYNTHETIC_PASSWORD in str(event.data) for event in result.trace)
    assert any(_SYNTHETIC_PASSWORD in str(record["messages"]) for record in recorder.records)
    report=aggregate_private_run(
        result=result,api_tool=api,
        arm="parity",scene_index=0,
        repeat_index=int(bool(fail_after_password)),
        official_task_success=None,
        nested_tests=None,elapsed_s=None)
    assert report["raw_agent_trace_exported"] is False
    assert report["raw_model_recording_exported"] is False
    assert report["no_plaintext_or_secret_hashes_in_artifact"] is True
    if fail_after_password:
        assert report["stop_reason"]=="model_error"
        assert report["auth_action_counts"]["supervisor_passwords"]["succeeded"]==1
    else:
        assert report["stop_reason"]=="final"
        assert report["auth_action_counts"]["supervisor_profile"]["succeeded"]==1
        assert report["auth_action_counts"]["supervisor_passwords"]["succeeded"]==1
        assert report["auth_action_counts"]["app_login"]["succeeded"]==1
    # Force disappearance of in-memory secret-bearing object references
    # before any artifact or log is written.
    del result,recorder,api,world
    return report


def run_smoke(output:Path)->None:
    if output.exists():raise FileExistsError("do not overwrite")
    with tempfile.TemporaryDirectory(prefix="appworld-synthetic-private-") as private_dir:
        private=Path(private_dir)
        fake_stdout,fake_stderr=io.StringIO(),io.StringIO()
        with redirect_stdout(fake_stdout),redirect_stderr(fake_stderr):
            first=exercise_synthetic_private_workflow(private/"ok",fail_after_password=False)
            second=exercise_synthetic_private_workflow(private/"error",fail_after_password=True)
        # SDK/model debug output is NOT forwarded to Actions logs.
        fake_stdout.close();fake_stderr.close()
    # Only explicitly safe summaries are emitted and the private directory
    # containing model histories has already been deleted.
    payload={"protocol":"APPWORLD-PARITY-END-TO-END-SYNTHETIC-PRIVACY-V1",
             "n_synthetic_scenarios":2,
             "succeeded_with_credentials_and_login":True,
             "safe_agent_reports":[first,second]}
    dump=json.dumps(payload,sort_keys=True,indent=2,allow_nan=False)
    assert all(secret not in dump for secret in _SECRET)
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(dump+"\n")
    on_disk=output.read_text()
    assert all(secret not in on_disk for secret in _SECRET)
    assert not any(p.is_dir() for p in output.parent.iterdir() if p.name.startswith("private"))
    # NEVER include any user/model text from the private runner in logs.
    print("SYNTHETIC_PARITY_CREDENTIAL_TRACE_PRIVACY",json.dumps({
        "n_scenarios":2,"raw_trace_exported":False,
        "real_Qwen_calls":0,"model_error_message_exported":False,
        "auth_behavior_fake_only":True},sort_keys=True))


def main():
    import argparse
    p=argparse.ArgumentParser()
    p.add_argument("--out",required=True,type=Path)
    args=p.parse_args()
    try:run_smoke(args.out)
    except Exception as exc:
        print("SYNTHETIC_PARITY_PRIVACY_FAIL_CLOSED",safe_exception_category(exc))
        raise SystemExit(1) from None


if __name__=="__main__":
    main()
